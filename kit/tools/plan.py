#!/usr/bin/env python3
"""Script -> timed config skeleton.
usage: python3 tools/plan.py script.txt [--wps 3.0] [--out config.skeleton.js]
script.txt (one block per pair; first line of a block = the names + question, then what A does, then what B does):
    # Docker vs Kubernetes
    Docker, Kubernetes. What's the difference?
    Docker runs your application in a container.
    Kubernetes runs and scales multiple containers across servers.
Optional explicit markers instead of position:  'A: ...' and 'B: ...' lines (several lines allowed per side).
Times are ESTIMATES (words / wps, default 3.0). Replace with the creator's real timestamps when given.
Prints a table and writes a skeleton using the measured state machine (names, yellow label, cut, focus L, focus R, neutral, next pair)."""
import sys, re, argparse, os, json
ap = argparse.ArgumentParser(); ap.add_argument('script'); ap.add_argument('--wps', type=float, default=3.0); ap.add_argument('--out', default='config.skeleton.js'); ap.add_argument('--legacy', action='store_true', help='low-level skeleton without pairFrame'); a = ap.parse_args()
here = os.path.dirname(os.path.abspath(__file__)); TOP = None
for cand in (os.path.join(here, '..', 'topics.json'), os.path.join(here, '..', '..', 'reference', 'topics.json')):
    if os.path.exists(cand): TOP = json.load(open(cand)); break
norm = lambda s: re.sub(r'[^a-z0-9]', '', s.lower())
def recipe(l, r):
    if not TOP: return None
    for t in TOP['topics']:
        if (norm(t['a']) in norm(l) or norm(l) in norm(t['a'])) and (norm(t['b']) in norm(r) or norm(r) in norm(t['b'])): return t
    return None
words = lambda t: len(re.findall(r"[\w'’]+", t))
pairs = []; cur = None
for raw in open(a.script, encoding='utf-8'):
    line = raw.strip()
    if not line: continue
    if line.startswith('#'):
        title = line.lstrip('#').strip(); m = re.split(r'\s+vs\.?\s+', title, flags=re.I)
        cur = {'title': title, 'L': m[0].strip() if len(m) > 1 else title, 'R': m[1].strip() if len(m) > 1 else '', 'lines': [], 'A': [], 'B': []}; pairs.append(cur); continue
    if cur is None: continue
    if re.match(r'^A\s*:', line): cur['A'].append(re.sub(r'^A\s*:\s*', '', line))
    elif re.match(r'^B\s*:', line): cur['B'].append(re.sub(r'^B\s*:\s*', '', line))
    else: cur['lines'].append(line)
out = ["/* generated by tools/plan.py (estimated at %.1f words/s). Fill every TODO; keep the state machine. */" % a.wps, "window.DURATION = 0; // set below"]
rows = []; t0 = 0.0
if not a.legacy:
    out = ["/* generated by tools/plan.py (estimated at %.1f words/s). Every element ENTERS when it is spoken (never pre-placed); use stack() when the diagram crowds; something moves every <= 0.7 s. */" % a.wps, "window.DURATION = 0;"]
if not a.legacy:
    for n, p in enumerate(pairs, 1):
        intro = p['lines'][0] if p['lines'] else ''
        rest = p['lines'][1:]
        if not p['A'] and not p['B']:
            half = max(1, (len(rest) + 1) // 2) if len(rest) > 1 else 1
            p['A'], p['B'] = rest[:half] if len(rest) > 1 else rest[:1], rest[half:] if len(rest) > 1 else []
        dA = max(words(' '.join(p['A'])) / a.wps, 4.0); dB = max(words(' '.join(p['B'])) / a.wps, 4.0)
        first = n == 1; P = t0; c = P + 2.85; fb = c + dA; neu = fb + dB; nxt = neu + 1.5
        rows.append((n, p['title'], round(P, 2), round(c, 2), round(fb, 2), round(neu, 2), round(nxt, 2)))
        rc = recipe(p['L'], p['R'])
        out.append(f"\n/* ---------- PAIR {n}: {p['title']} ---------- */")
        if rc:
            out.append(f"// RECIPE #{rc['n']} ({rc['type']}): LEFT: {rc['left']}")
            out.append(f"//                      RIGHT: {rc['right']}")
            out.append(f"// assets: {rc['assets']}" + (f"   | worked example: {rc['demo']}" if rc['demo'] else ''))
        intro_args = (f"first:true,tl:['<slug>','<hex>',.8],tr:['<slug>','<hex>',.8]" if first else "hl:hero('<lucide>'),hr:hero('<lucide>')")
        out.append(f"let T{n} = pairFrame({P:.2f},{{{intro_args},L:'{p['L']}',R:'{p['R']}',dA:{dA:.1f},dB:{dB:.1f}}});")
        for side, key, ref, dur in (('L', 'A', 'a', dA), ('R', 'B', 'b', dB)):
            out.append(f"// {key} ({dur:.1f}s): \"{' '.join(p[key])[:100]}\"")
            k = max(5, min(9, int((dur - .8) / .6))); step = (dur - 1.2) / k
            out.append(f"//   one beat every ~{step:.1f}s; enter each element at the moment its word is spoken; earlier ones shrink away via stack('{side}',{{mode:'trail'}}) if it crowds")
            for i in range(k): out.append(f"add('{side}',{{at:T{n}.{ref}({.45+i*step:.2f}),kind:'pop',x:0,y:0,w:0,h:0,html:/*TODO beat {i+1}*/IC.ok()}});")
        t0 = nxt
    out[1] = f"window.DURATION = {t0 - 1.2:.1f};"
    open(a.out, 'w').write('\n'.join(out) + '\n')
    print('pair | title | start | cut->focus A | focus B | settle | next'); [print(' | '.join(str(x) for x in r)) for r in rows]
    print('wrote', a.out, '| total', round(t0 - 1.2, 1), 's (estimate)'); sys.exit(0)
    

for n, p in enumerate(pairs, 1):
    intro = p['lines'][0] if p['lines'] else ''
    rest = p['lines'][1:]
    if not p['A'] and not p['B']:
        half = max(1, (len(rest) + 1) // 2) if len(rest) > 1 else 1
        p['A'], p['B'] = rest[:half] if len(rest) > 1 else rest[:1], rest[half:] if len(rest) > 1 else []
    dI = max(words(intro) / a.wps, 2.4); dA = max(words(' '.join(p['A'])) / a.wps, 2.0); dB = max(words(' '.join(p['B'])) / a.wps, 2.0)
    first = n == 1
    wtd_at = round(t0 + max(dI - 1.0, 1.84), 2); cut_t = round(wtd_at + 0.84, 2)
    fA = cut_t; fB = round(cut_t + dA - 0.1, 2); neu = round(fB + dB + 0.1, 2); nxt = round(neu + 1.3, 2)
    rows.append((n, p['title'], t0, wtd_at, cut_t, fB, neu, nxt))
    out.append(f"\n/* ---------- PAIR {n}: {p['title']}  (intro {dI:.1f}s, A {dA:.1f}s, B {dB:.1f}s) ---------- */")
    if first: out.append(f"boxPop('L',{t0:.2f});boxPop('R',{t0+.75:.2f});")
    out.append(f"// TODO intro (tool with a logo -> tile; concept -> hero icon):")
    out.append(f"//   tile('L',{t0:.2f},'<slug>','white','<hex>',{{fit:.8}});tile('R',{t0+.75:.2f},'<slug>','white','<hex>');   or   add('L',{{at:{t0+.1:.2f},kind:'pop',x:70,y:70,w:140,h:140,html:IC.hero('<lucide>')}});")
    out.append(f"label('L',{t0+.12:.2f},'{p['L']}',{{until:{wtd_at-.04:.2f}}});label('R',{t0+.87:.2f},'{p['R']}',{{until:{wtd_at-.04:.2f}}});")
    out.append(f"wtd({wtd_at:.2f},{cut_t:.2f});cut({cut_t:.2f});")
    for side, key, ft, dur, nm in (('L', 'A', fA, dA, p['L']), ('R', 'B', fB, dB, p['R'])):
        out.append(f"focus('{side}',{ft:.2f});label('{side}',{ft+.4:.2f},'{nm}',{{dur:.3,{'until:%.2f,out:.25' % (fB+.25) if side=='L' else ''}}});".replace(",}", "}"))
        k = max(2, min(5, int((dur - 1.0) / 0.9))); step = (dur - 1.2) / k
        out.append(f"// {key}: \"{' '.join(p[key])[:90]}\"")
        for i in range(k): out.append(f"add('{side}',{{at:{ft+.5+i*step:.2f},kind:'pop',x:0,y:0,w:0,h:0,html:/*TODO*/IC.container('docker')}});   // piece {i+1}: appears ~0.2s before its word")
    out.append(f"neutral({neu:.2f});label('L',{neu+.25:.2f},'{p['L']}',{{dur:.3}});cut({nxt:.2f});")
    t0 = nxt
out[1] = f"window.DURATION = {t0:.1f};"
open(a.out, 'w').write('\n'.join(out) + '\n')
print('pair | title | start | yellow | cut->focus A | focus B | settle | next'); [print(' | '.join(str(round(x, 2)) if isinstance(x, float) else str(x) for x in r)) for r in rows]
print('wrote', a.out, '| total', round(t0, 1), 's (estimate)')
